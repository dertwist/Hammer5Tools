# Comments are ordinary properties that may repeat as comment, comment_2, ...
_INDEXED_SUFFIX = re.compile(r"_\d+$")


def get_tooltip(key: str) -> str:
    """Tooltip for a property key, or an empty string when none is known.

    Repeatable keys (comment_2, comment_3) fall back to their base key.
    """
    if not key:
        return ""
    text = SOUNDEVENT_TOOLTIPS.get(key)
    if text is not None:
        return text
    return SOUNDEVENT_TOOLTIPS.get(_INDEXED_SUFFIX.sub("", key), "")

